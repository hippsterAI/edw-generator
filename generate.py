def dim_value_exprs(d: Dimension) -> tuple[dict[str, str], list[str]]:
    """
    Per-attribute T-SQL value expression over the staging row alias `src`
    (and helper.CodeMapping aliases), plus the join clauses those need.
    """
    exprs: dict[str, str] = {}
    joins: list[str] = []
    for a in d.attributes:
        if a.mapping:
            alias = f"map_{a.name}"
            joins.append(f"            LEFT JOIN helper.CodeMapping AS {alias}\n"
                         f"                   ON {alias}.MappingName = {q(a.mapping)}\n"
                         f"                  AND {alias}.SourceSystemName = @SourceSystemName\n"
                         f"                  AND {alias}.SourceCode = CONVERT(varchar(50), src.{a.name})")
            exprs[a.name] = f"COALESCE(map_{a.name}.StandardCode, src.{a.name})"
        elif a.mapping_name_of:
            exprs[a.name] = f"COALESCE(map_{a.mapping_name_of}.StandardName, src.{a.mapping_name_of})"
        elif a.expression:
            exprs[a.name] = a.expression  # placeholders resolved below
        else:
            exprs[a.name] = f"src.{a.name}"
    # resolve {Placeholder} references in expressions against the other expressions
    for a in d.attributes:
        if a.expression:
            e = a.expression
            for other, oe in exprs.items():
                if other != a.name:
                    e = e.replace("{" + other + "}", f"({oe})")
            exprs[a.name] = e
    return exprs, joins


def gen_dim_proc(model: Model, d: Dimension) -> str:
    proc = f"etl.Dim_{d.name}_InsertUpdate"
    exprs, joins = dim_value_exprs(d)
    key_cols = [(c.name, c.type) for c in d.source_key_columns]
    key = key_expr(key_cols, "src")
    not_null = " AND ".join(f"src.{n} IS NOT NULL" for n, _ in key_cols)
    scd1, scd2 = d.scd_attributes(1), d.scd_attributes(2)
    width = max(len(a.name) for a in d.attributes) + 1

    inner_cols = ",\n".join(f"                {a.name:<{width}}= CAST({exprs[a.name]} AS {a.type})" for a in d.attributes)
    attr_names = ", ".join(a.name for a in d.attributes)
    hash1, hash2 = hash_expr(model, scd1, "s"), hash_expr(model, scd2, "s")
    conf = [d.conf(s) for s in ("SourceSystemName", "SourceSystemKey", "SCDType1HashValue", "SCDType2HashValue",
                                "ActiveRecordFlag", "StartEffectiveDate", "EndEffectiveDate", "LastUpdatedDateTime")]
    ssn, ssk, h1, h2, active, start, end, upd = conf
    eot = q(model.settings["end_of_time"])
    join_src = "\n".join(joins)

    body = f"""{source_system_lookup(d.staging_table)}
        -- 1. Shape the source: one row per source key, mapped/derived values, both hashes.
        IF OBJECT_ID('tempdb..#Source') IS NOT NULL DROP TABLE #Source;
        SELECT
            s.SourceSystemKey,
            {attr_names},
            SCDType1HashValue = {hash1},
            SCDType2HashValue = {hash2}
        INTO #Source
        FROM (
            SELECT
                SourceSystemKey = CAST({key} AS varchar(200)),
{inner_cols},
                RowNumber = ROW_NUMBER() OVER (PARTITION BY {key} ORDER BY (SELECT NULL))
            FROM {d.staging} AS src
{join_src}
            WHERE {not_null}
        ) AS s
        WHERE s.RowNumber = 1;
        CREATE UNIQUE CLUSTERED INDEX IX_Source ON #Source (SourceSystemKey);

        BEGIN TRANSACTION;
"""
    if scd2:
        body += f"""
        -- 2. SCD Type 2: close the active row when a Type 2 attribute changed.
        UPDATE d
           SET d.{end} = @LoadDate,
               d.{active} = 'N',
               d.{upd} = SYSDATETIME()
          FROM {d.table} AS d
          JOIN #Source AS s ON s.SourceSystemKey = d.{ssk}
         WHERE d.{ssn} = @SourceSystemName
           AND d.{active} = 'Y'
           AND d.{h2} <> s.SCDType2HashValue;
        SET @RowsExpired = @@ROWCOUNT;
"""
    body += f"""
        -- 3. Insert every source row that has no active dimension row (new keys and re-opened Type 2 keys).
        INSERT {d.table} ({attr_names}, {', '.join(conf)})
        SELECT {', '.join('s.' + a.name for a in d.attributes)},
               @SourceSystemName, s.SourceSystemKey, s.SCDType1HashValue, s.SCDType2HashValue,
               'Y', @LoadDate, {eot}, SYSDATETIME()
          FROM #Source AS s
         WHERE NOT EXISTS (SELECT 1 FROM {d.table} AS d
                            WHERE d.{ssk} = s.SourceSystemKey
                              AND d.{ssn} = @SourceSystemName
                              AND d.{active} = 'Y');
        SET @RowsInserted = @@ROWCOUNT;
"""
    if scd1:
        sets = ",\n".join(f"               d.{a.name} = s.{a.name}" for a in scd1)
        body += f"""
        -- 4. SCD Type 1: overwrite in place on every version of the key.
        UPDATE d
           SET
{sets},
               d.{h1} = s.SCDType1HashValue,
               d.{upd} = SYSDATETIME()
          FROM {d.table} AS d
          JOIN #Source AS s ON s.SourceSystemKey = d.{ssk}
         WHERE d.{ssn} = @SourceSystemName
           AND d.{h1} <> s.SCDType1HashValue;
        SET @RowsUpdated = @@ROWCOUNT;
"""
    body += "\n        COMMIT TRANSACTION;\n"
    return stub_proc(proc) + proc_prologue(proc, d.table) + body + PROC_EPILOGUE


def fact_select(model: Model, f: Fact) -> str:
    """The INSERT ... SELECT shared by full and partial refresh."""
    unk = model.settings["unknown_member_key"]
    width = max(len(c.name) for c in f.all_columns) + 1
    sel = []
    for dk in f.dimension_keys:
        sel.append(f"               {dk.column:<{width}}= ISNULL({dk.role}.{dk.dimension.key}, {unk})")
    for m in f.measures:
        sel.append(f"               {m.name:<{width}}= src.{m.name}")
    key_cols = [(n, f.staging_column(n).type) for n in f.source_key]
    sel.append(f"               {f.conf('SourceSystemName'):<{width}}= @SourceSystemName")
    sel.append(f"               {f.conf('SourceSystemKey'):<{width}}= CAST({key_expr(key_cols, 'src')} AS varchar(200))")
    sel.append(f"               {f.conf('LastUpdatedDateTime'):<{width}}= SYSDATETIME()")
    joins = []
    for dk in f.dimension_keys:
        d = dk.dimension
        cols = [(s, c.type) for s, c in zip(dk.source, d.source_key_columns)]
        joins.append(f"          LEFT JOIN {d.table} AS {dk.role}\n"
                     f"                 ON {dk.role}.{d.conf('SourceSystemKey')} = {key_expr(cols, 'src')}\n"
                     f"                AND {dk.role}.{d.conf('ActiveRecordFlag')} = 'Y'")
    names = [c.name for c in f.all_columns if c.name != f.key]
    return (f"        INSERT {f.table} ({', '.join(names)})\n"
            f"        SELECT\n" + ",\n".join(sel) + f"\n          FROM {f.staging} AS src\n" + "\n".join(joins) + ";\n")


def gen_fact_full_proc(model: Model, f: Fact) -> str:
    proc = f"etl.Fact_{f.name}_FullRefresh"
    body = (source_system_lookup(f.staging_table)
            + "\n        BEGIN TRANSACTION;\n"
            + f"        TRUNCATE TABLE {f.table};\n\n"
            + fact_select(model, f)
            + "        SET @RowsInserted = @@ROWCOUNT;\n        COMMIT TRANSACTION;\n")
    return stub_proc(proc) + proc_prologue(proc, f.table) + body + PROC_EPILOGUE


def gen_fact_partial_proc(model: Model, f: Fact) -> str:
    proc = f"etl.Fact_{f.name}_PartialRefresh"
    dk = f.dimension_key(f.partial_refresh_role)
    d = dk.dimension
    unk = model.settings["unknown_member_key"]
    cols = [(s, c.type) for s, c in zip(dk.source, d.source_key_columns)]
    body = (source_system_lookup(f.staging_table)
            + f"""
        -- Scope: every {dk.role} present in staging is replaced in full.
        IF OBJECT_ID('tempdb..#Scope') IS NOT NULL DROP TABLE #Scope;
        SELECT DISTINCT {dk.column} = ISNULL({dk.role}.{d.key}, {unk})
          INTO #Scope
          FROM {f.staging} AS src
          LEFT JOIN {d.table} AS {dk.role}
                 ON {dk.role}.{d.conf('SourceSystemKey')} = {key_expr(cols, 'src')}
                AND {dk.role}.{d.conf('ActiveRecordFlag')} = 'Y';

        BEGIN TRANSACTION;
        DELETE f FROM {f.table} AS f WHERE f.{dk.column} IN (SELECT {dk.column} FROM #Scope);
        SET @RowsExpired = @@ROWCOUNT;

""" + fact_select(model, f)
            + "        SET @RowsInserted = @@ROWCOUNT;\n        COMMIT TRANSACTION;\n")
    return stub_proc(proc) + proc_prologue(proc, f.table) + body + PROC_EPILOGUE


def gen_etl_procedures(model: Model) -> str:
    out = [header("09 ETL PROCEDURES: staging -> dim/fact. All transform logic lives here.")]
    for d in model.dims:
        out.append(gen_dim_proc(model, d))
    for f in model.facts:
        out.append(gen_fact_full_proc(model, f))
        if f.large:
            out.append(gen_fact_partial_proc(model, f))
    return "\n".join(out)


