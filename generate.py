def upsert(table: str, where: str, values: dict[str, str]) -> str:
    """Idempotent catalog row: insert when absent, otherwise refresh every column."""
    cols = ", ".join(values)
    vals = ", ".join(values.values())
    sets = ",\n           ".join(f"{k} = {v}" for k, v in values.items())
    return (f"IF NOT EXISTS (SELECT 1 FROM {table} WHERE {where})\n"
            f"    INSERT {table} ({cols}) VALUES ({vals});\nELSE\n"
            f"    UPDATE {table}\n       SET {sets},\n           LastUpdatedDateTime = SYSDATETIME()\n"
            f"     WHERE {where};\nGO\n")


def gen_catalog_seed(model: Model) -> str:
    out = [header("11 CATALOG SEED: every entity registered as metadata (the pipeline runs off these rows)")]
    for i, d in enumerate(model.dims, start=1):
        out.append(upsert("catalog.Dimensions", f"DimensionName = {q(d.name)}", {
            "DimensionName": q(d.name), "SchemaName": "'dim'", "TableName": q(d.name),
            "StagingSchemaName": "'stg'", "StagingTableName": q(d.staging_table),
            "TransformProcedureName": q(f"Dim_{d.name}_InsertUpdate"), "LoadOrder": str(i), "EnabledFlag": "'Y'"}))
    for i, f in enumerate(model.facts, start=1):
        out.append(upsert("catalog.Facts", f"FactName = {q(f.name)}", {
            "FactName": q(f.name), "SchemaName": "'fact'", "TableName": q(f.name),
            "StagingSchemaName": "'stg'", "StagingTableName": q(f.staging_table),
            "FullRefreshProcedureName": q(f"Fact_{f.name}_FullRefresh"),
            "PartialRefreshProcedureName": q(f"Fact_{f.name}_PartialRefresh") if f.large else "NULL",
            "LargeFactFlag": "'Y'" if f.large else "'N'", "LoadOrder": str(i), "EnabledFlag": "'Y'"}))
    for kind, entities in (("Dimension", model.dims), ("Fact", model.facts)):
        for e in entities:
            out.append(upsert("catalog.StagingTable", f"SchemaName = 'stg' AND TableName = {q(e.staging_table)}", {
                "SchemaName": "'stg'", "TableName": q(e.staging_table), "SourceSystemName": q(e.source_system),
                "SourceObjectName": q(e.source_object), "TargetEntityTypeName": q(kind),
                "TargetEntityName": q(e.name), "EnabledFlag": "'Y'"}))
    return "\n".join(out)


