def gen_drop_all(model: Model) -> str:
    out = [header("99 DROP ALL: reverse dependency order, every step guarded")]

    def drop(kind: str, name: str, code: str) -> str:
        return f"IF OBJECT_ID('{name}', '{code}') IS NOT NULL DROP {kind} {name};\n"

    out.append("-- foreign keys")
    for f in model.facts:
        for dk in f.dimension_keys:
            n = fk_name(f, dk)
            out.append(f"IF EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = '{n}') ALTER TABLE {f.table} DROP CONSTRAINT {n};")
    out.append("GO\n-- views")
    for f in model.facts:
        out.append(drop("VIEW", f"data.{f.name}", "V"))
    for role, _ in model.roles:
        out.append(drop("VIEW", f"lookup.{role}", "V"))
    out.append("GO\n-- procedures")
    for p in ("etl.Load_Warehouse", "etl.Load_Facts", "etl.Load_Dimensions"):
        out.append(drop("PROCEDURE", p, "P"))
    for f in model.facts:
        out.append(drop("PROCEDURE", f"etl.Fact_{f.name}_FullRefresh", "P"))
        out.append(drop("PROCEDURE", f"etl.Fact_{f.name}_PartialRefresh", "P"))
    for d in model.dims:
        out.append(drop("PROCEDURE", f"etl.Dim_{d.name}_InsertUpdate", "P"))
    for p in ("control.PrepareStagingTable", "control.ValidateTableName", "control.ExecutionFailure",
              "control.ExecutionCompletion", "control.ExecutionStart"):
        out.append(drop("PROCEDURE", p, "P"))
    out.append("GO\n-- tables")
    for f in model.facts:
        out.append(drop("TABLE", f.table, "U"))
    for d in model.dims:
        out.append(drop("TABLE", d.table, "U"))
    for e in [*model.dims, *model.facts]:
        out.append(drop("TABLE", e.staging, "U"))
    for t in ("helper.CodeMapping", "helper.SchoolName", "helper.DeliveryType", "helper.AgeBandDefinition",
              "control.ProcessLog", "catalog.StagingTable", "catalog.Facts", "catalog.Dimensions"):
        out.append(drop("TABLE", t, "U"))
    out.append("GO\n-- schemas")
    for s in reversed(SCHEMAS):
        out.append(f"IF EXISTS (SELECT 1 FROM sys.schemas WHERE name = '{s}') EXEC('DROP SCHEMA [{s}]');")
    out.append("GO\n")
    return "\n".join(out)


