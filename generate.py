def gen_schemas(model: Model) -> str:
    out = [header("01 SCHEMAS")]
    for s in SCHEMAS:
        out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.schemas WHERE name = '{s}')\n"
                   f"    EXEC('CREATE SCHEMA [{s}] AUTHORIZATION dbo');\nGO\n")
    return "\n".join(out)


