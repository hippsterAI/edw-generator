# 08 data views: one consumption view per fact
# ---------------------------------------------------------------------------

def data_column(dk: DimensionKey, c: Column) -> str:
    """Role-qualified name so a wide join can never collide."""
    name = role_column(dk.role, dk.dimension.name, c.name)
    return name if name.startswith(dk.role) else f"{dk.role}{name}"


def data_view_columns(f: Fact) -> list[tuple[str, str]]:
    """(output name, source expression) for the data view -- used by validate.py too."""
    cols = [(f.key, f"f.{f.key}")]
    for dk in f.dimension_keys:
        for c in dk.dimension.attributes:
            cols.append((data_column(dk, c), f"{dk.role}.{role_column(dk.role, dk.dimension.name, c.name)}"))
    for m in f.measures:
        cols.append((m.name, f"f.{m.name}"))
    for c in f.conformance_columns:
        cols.append((c.name, f"f.{c.name}"))
    return cols


def gen_data_views(model: Model) -> str:
    out = [header("08 DATA VIEWS: one consumption view per fact, keys resolved to names")]
    for f in model.facts:
        view = f"data.{f.name}"
        cols = data_view_columns(f)
        width = max(len(n) for n, _ in cols) + 1
        sel = ",\n".join(f"    {n:<{width}}= {e}" for n, e in cols)
        joins = "\n".join(f"JOIN lookup.{dk.role} AS {dk.role} ON {dk.role}.{dk.column} = f.{dk.column}"
                          for dk in f.dimension_keys)
        out.append(stub_view(view) + f"ALTER VIEW {view}\nAS\nSELECT\n{sel}\nFROM {f.table} AS f\n{joins};\nGO\n")
    return "\n".join(out)


