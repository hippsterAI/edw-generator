def gen_facts(model: Model) -> str:
    out = [header("05 FACTS: tables and indexes")]
    for f in model.facts:
        cols = f.all_columns
        out.append(f"-- {f.table}: {f.description}  (grain: {f.grain})\n"
                   f"IF OBJECT_ID('{f.table}', 'U') IS NULL\n"
                   f"CREATE TABLE {f.table} (\n{column_ddl(cols, identity=f.key)},\n"
                   f"    CONSTRAINT PK_fact_{f.name} PRIMARY KEY CLUSTERED ({f.key})\n);\nGO\n")
        keys = [f"{r}Key" for r in f.index_keys]
        ix = f"IX_fact_{f.name}_" + "_".join(keys)
        out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = '{ix}' AND object_id = OBJECT_ID('{f.table}'))\n"
                   f"    CREATE NONCLUSTERED INDEX {ix} ON {f.table} ({', '.join(keys)});\nGO\n")
    return "\n".join(out)


