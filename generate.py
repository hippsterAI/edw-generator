# ---------------------------------------------------------------------------
# Small T-SQL rendering helpers
# ---------------------------------------------------------------------------

def q(s: str) -> str:
    """Single-quote a T-SQL string literal."""
    return "'" + s.replace("'", "''") + "'"


def to_text(expr: str, sql_type: str) -> str:
    """Deterministic text form of a value, used for hashes and source keys."""
    bt = base_type(sql_type)
    if bt == "date":
        return f"CONVERT(varchar(10), {expr}, 23)"
    if bt in ("datetime", "datetime2", "smalldatetime"):
        return f"CONVERT(varchar(27), {expr}, 121)"
    if bt == "time":
        return f"CONVERT(varchar(16), {expr}, 114)"
    return f"CONVERT(nvarchar(200), {expr})"


def key_expr(cols: list[tuple[str, str]], alias: str) -> str:
    """CONCAT of the typed text of each source column, '|' separated."""
    parts = [to_text(f"{alias}.{n}", t) for n, t in cols]
    if len(parts) == 1:
        return parts[0]
    joined = ", '|', ".join(parts)
    return f"CONCAT({joined})"


def hash_expr(model: Model, cols: list[Column], alias: str) -> str:
    alg = q(model.settings["hash_algorithm"])
    if not cols:
        return f"HASHBYTES({alg}, '')"
    parts = [f"ISNULL({to_text(f'{alias}.{c.name}', c.type)}, '')" for c in cols]
    if len(parts) == 1:
        return f"HASHBYTES({alg}, {parts[0]})"
    sep = ", '|', "
    return f"HASHBYTES({alg}, CONCAT({sep.join(parts)}))"


def null_spec(c: Column) -> str:
    return "NULL" if c.nullable else "NOT NULL"


def unknown_value(c: Column) -> str:
    """Literal for the Unknown member row (surrogate key -1)."""
    bt = base_type(c.type)
    if c.name.endswith("Flag"):
        return "'N'"
    if bt in ("varchar", "nvarchar", "char", "nchar"):
        n = type_length(c.type) or 1
        return q("Unknown"[:n])
    return "NULL"


def stub_proc(name: str) -> str:
    return (f"IF OBJECT_ID('{name}', 'P') IS NULL\n"
            f"    EXEC('CREATE PROCEDURE {name} AS BEGIN SET NOCOUNT ON; END');\nGO\n")


def stub_view(name: str) -> str:
    return (f"IF OBJECT_ID('{name}', 'V') IS NULL\n"
            f"    EXEC('CREATE VIEW {name} AS SELECT Placeholder = 1');\nGO\n")


def header(title: str) -> str:
    bar = "-" * 77
    return f"-- {bar}\n-- {title}\n-- GENERATED by generate.py from model.yaml. Do not edit by hand.\n-- {bar}\n"


def column_ddl(cols: list[Column], identity: str | None = None) -> str:
    width = max(len(c.name) for c in cols) + 1
    lines = []
    for c in cols:
        if c.name == identity:
            lines.append(f"    {c.name:<{width}} int IDENTITY(1,1) NOT NULL")
        else:
            lines.append(f"    {c.name:<{width}} {c.type} {null_spec(c)}")
    return ",\n".join(lines)


