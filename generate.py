def gen_staging(model: Model) -> str:
    out = [header("03 STAGING: 1:1 landing tables, no transformation")]
    for entity in [*model.dims, *model.facts]:
        cols = entity.staging_columns
        out.append(f"-- {entity.staging}  <-  {entity.source_system}.{entity.source_object}\n"
                   f"IF OBJECT_ID('{entity.staging}', 'U') IS NULL\n"
                   f"CREATE TABLE {entity.staging} (\n{column_ddl(cols)}\n);\nGO\n")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# 04 dimensions
# ---------------------------------------------------------------------------

def gen_dimensions(model: Model) -> str:
    out = [header("04 DIMENSIONS: tables, indexes, Unknown member rows")]
    unk = model.settings["unknown_member_key"]
    alg = q(model.settings["hash_algorithm"])
    for d in model.dims:
        cols = d.all_columns
        out.append(f"-- {d.table}: {d.description}\n"
                   f"IF OBJECT_ID('{d.table}', 'U') IS NULL\n"
                   f"CREATE TABLE {d.table} (\n{column_ddl(cols, identity=d.key)},\n"
                   f"    CONSTRAINT PK_dim_{d.name} PRIMARY KEY CLUSTERED ({d.key})\n);\nGO\n")
        ix = f"IX_dim_{d.name}_SourceSystemKey"
        out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = '{ix}' AND object_id = OBJECT_ID('{d.table}'))\n"
                   f"    CREATE NONCLUSTERED INDEX {ix} ON {d.table}\n"
                   f"        ({d.conf('SourceSystemKey')}, {d.conf('SourceSystemName')}, {d.conf('ActiveRecordFlag')});\nGO\n")
        # Unknown member so every fact FK always resolves.
        names = ", ".join(c.name for c in cols)
        values = [str(unk)] + [unknown_value(a) for a in d.attributes] + [
            "'Unknown'", "'Unknown'", f"HASHBYTES({alg}, 'Unknown')", f"HASHBYTES({alg}, 'Unknown')",
            "'Y'", "'1900-01-01'", q(model.settings["end_of_time"]), "SYSDATETIME()"]
        out.append(f"IF NOT EXISTS (SELECT 1 FROM {d.table} WHERE {d.key} = {unk})\nBEGIN\n"
                   f"    SET IDENTITY_INSERT {d.table} ON;\n"
                   f"    INSERT {d.table} ({names})\n    VALUES ({', '.join(values)});\n"
                   f"    SET IDENTITY_INSERT {d.table} OFF;\nEND\nGO\n")
    return "\n".join(out)


