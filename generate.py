def fk_name(f: Fact, dk: DimensionKey) -> str:
    return f"FK_fact_{f.name}_{dk.column}"


def gen_foreign_keys(model: Model) -> str:
    out = [header("06 FOREIGN KEYS: fact -> dimension")]
    for f in model.facts:
        for dk in f.dimension_keys:
            name = fk_name(f, dk)
            out.append(f"IF NOT EXISTS (SELECT 1 FROM sys.foreign_keys WHERE name = '{name}')\n"
                       f"    ALTER TABLE {f.table} WITH CHECK ADD CONSTRAINT {name}\n"
                       f"        FOREIGN KEY ({dk.column}) REFERENCES {dk.dimension.table} ({dk.dimension.key});\nGO\n")
    return "\n".join(out)


# ---------------------------------------------------------------------------
# 07 lookup views: one per dimension role
# ---------------------------------------------------------------------------

def gen_lookup_views(model: Model) -> str:
    out = [header("07 LOOKUP VIEWS: one view per dimension role (never duplicate a dim table)")]
    for role, d in model.roles:
        view = f"lookup.{role}"
        width = max(len(role_column(role, d.name, c.name)) for c in d.all_columns) + 1
        sel = ",\n".join(f"    {role_column(role, d.name, c.name):<{width}}= d.{c.name}" for c in d.all_columns)
        note = "" if role == d.name else f"  -- {d.name} played as {role}"
        out.append(stub_view(view) + f"ALTER VIEW {view}{note}\nAS\nSELECT\n{sel}\nFROM {d.table} AS d;\nGO\n")
    return "\n".join(out)


